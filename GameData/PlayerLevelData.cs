    public const int MaxLevel = 400;

    /// <summary>
    /// 添加经验，返回新的等级和经验。
    /// </summary>
    public static (int level, long exp, int levelsGained) AddExperience(int currentLevel, long currentExp, long addedExp)
    {
        var level = currentLevel;
        var exp = currentExp + addedExp;
        var levelsGained = 0;

        while (level < MaxLevel)
        {
            var idx = level - 1; // 数组索引从0开始，对应1级升2级
            if (idx < 0 || idx >= ExpToNextLevel.Length) break;
            var required = ExpToNextLevel[idx];
            if (required <= 0) break;
            if (exp < required) break;
            exp -= required;
            level++;
            levelsGained++;
        }

        if (level >= MaxLevel) exp = 0;
        return (level, exp, levelsGained);
    }
